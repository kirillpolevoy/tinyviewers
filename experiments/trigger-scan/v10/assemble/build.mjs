#!/usr/bin/env node
// v10 ASSEMBLY, step 2: write the pipeline's question set from assemble/decisions.json (decide.mjs).
//
//   node assemble/build.mjs   ->  v10/jev-set.js (generated module: Jev questions, concepts, combine rules,
//                                 thresholds) and v10/split.json (owner per v9 id + the evidence per concept)
//
// Nothing is chosen here; every choice (owner, phrasing, bundle, threshold) is decide.mjs's. This step only
// turns them into the shapes questions.js / select.js / sonnetq.js read, and refuses anything inconsistent.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { PRESENCE, EVENTS, DERIVED } from '../../v9/questions.js';
import { keysOf, show } from '../combine.js';
import { lintNoul } from '../lint.js';
import { conceptTargets } from './targets.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const V10 = path.resolve(here, '..');
const D = JSON.parse(fs.readFileSync(path.join(here, 'decisions.json'), 'utf8'));
const PRES = new Set(PRESENCE.map((p) => p.id));
const EVS = new Set(EVENTS.map((e) => e.id));
const SLOTS = ['<name>', '<danger>', '<villain>', '<child>', '{NAME}', '{DANGER}'];
const r4 = (x) => (x == null ? null : Math.round(x * 1e4) / 1e4);

const QUESTIONS = {};
const addQ = (defs) => {
  for (const [k, d] of Object.entries(defs)) {
    const f = lintNoul(d.q, { slots: SLOTS });
    if (f.length) throw new Error(`build: ${k} fails lint (${f.join(', ')}); decide.mjs should never pick it`);
    const row = { state: d.state, src: d.src, template: d.template || null, ...(d.fix_of ? { fix_of: d.fix_of } : {}), q: { type: 'noul', instructions: d.q.instructions, criteria: { true: d.q.criteria.true, false: d.q.criteria.false } } };
    if (QUESTIONS[k] && JSON.stringify(QUESTIONS[k]) !== JSON.stringify(row)) throw new Error(`build: ${k} defined twice differently`);
    QUESTIONS[k] = row;
  }
};

const CONCEPTS = {};
const assign = {};
for (const d of D.decisions) {
  const ev = {
    tier: d.tier, v9_owner: d.v9_owner, tournament_owner: d.tournament_owner,
    ...(d.jev ? { jev: { candidate: d.jev.id, threshold: d.jev.t, measured: d.jev.measured, ...(d.jev.fixed ? { lint_fixed: d.jev.fixed } : {}), precision: `${d.jev.all.hits}/${d.jev.all.fires}`, precision_p: r4(d.jev.all.precision), recall: `${d.jev.all.caught}/${d.jev.all.items}`, recall_p: r4(d.jev.all.recall), magic_films: `${d.jev.magic.hits}/${d.jev.magic.fires}`, wilson_lo: d.jev.wilson_lo } } : {}),
    ...(d.sonnet ? { sonnet: { ids: d.sonnet.ids, precision: `${d.sonnet.at_07.hits}/${d.sonnet.at_07.fires}`, precision_p: r4(d.sonnet.at_07.precision), recall: `${d.sonnet.at_07.caught}/${d.sonnet.at_07.items}`, recall_p: r4(d.sonnet.at_07.recall) } } : { sonnet: 'never asked' }),
    ...(d.reference_v9_at_07 ? { v9_wording_at_07: { precision: `${d.reference_v9_at_07.all.hits}/${d.reference_v9_at_07.all.fires}`, recall: `${d.reference_v9_at_07.all.caught}/${d.reference_v9_at_07.all.items}` } } : {}),
    strict_measured_only: d.strict_measured_only.owner === 'sonnet' ? 'sonnet' : `${d.strict_measured_only.jev?.id} @${d.strict_measured_only.jev?.t}`,
    tournament_best: d.tournament_best ? `${d.tournament_best.id} @${d.tournament_best.t}${d.tournament_best.eligible ? '' : ` (not eligible: ${Object.values(d.tournament_best.lint_fails ?? {}).flat().join('; ')})`}` : null,
  };
  const { targets, defs, assign: as } = conceptTargets(d);
  addQ(defs);
  Object.assign(assign, as);
  CONCEPTS[d.concept] = { owner: d.owner, group: d.group, film: d.film, v9_ids: d.v9_ids, targets, show: d.jev ? show(d.jev.expr) : null, evidence: ev };
}

// every universal v9 id is assigned exactly once
const universal = [...PRESENCE.map((p) => p.id), ...EVENTS.map((e) => e.id)];
for (const id of universal) if (!assign[id]) throw new Error(`build: no owner for v9 id ${id}`);
for (const id of Object.keys(assign)) if (!universal.includes(id)) throw new Error(`build: unknown v9 id ${id}`);
// every key read by a target is defined; every defined question is read
const read = new Set(Object.values(CONCEPTS).flatMap((c) => c.targets.flatMap((t) => [...keysOf(t.expr)])));
for (const k of read) if (!QUESTIONS[k]) throw new Error(`build: ${k} is read but not defined`);
for (const k of Object.keys(QUESTIONS)) if (!read.has(k)) throw new Error(`build: ${k} is defined but never read`);

const sonnetUsed = universal.filter((id) => assign[id] === 'sonnet');
const stamp = crypto.createHash('sha256').update(fs.readFileSync(path.join(here, 'decisions.json'))).digest('hex').slice(0, 12);
const header = `// GENERATED by assemble/build.mjs from assemble/decisions.json (sha256 ${stamp}); do not edit by hand.
// Re-run: node assemble/decide.mjs && node assemble/build.mjs
//
// v10 JEV SET. QUESTIONS: every Noul v10 asks Jev per scene (besides v9's mention, modifier, Score, kind and
// film-presence questions, which questions.js keeps unchanged), keyed as the phrasing tournament keyed them:
//   '<src>:<phrasing>@<state>'  src C = Claude rewrite, A = Astra rewrite, V = v9 wording; a '+' marks a
//   lint-fixed variant (assemble/fixrun/fixes.mjs); '#{item}' marks a film template, asked once per
//   generated film item. state = the minimal state it is asked in (questions.js statesFor).
// CONCEPTS: owner per concept (decide.mjs rule), and for Jev-owned ones the targets select.js tags: each is
// a combine.js expression over QUESTIONS keys with its own act threshold.
// fix_mode at generation: ${D.fix_mode}. ${D.fix_mode === 'proxy' ? 'Evidence marked measured:false rests on the ORIGINAL wording\'s answers (the lint-fixed wording was not measured: HTTP 402, no TypeSafe credits); measure before freezing (assemble/fixrun/run.mjs).' : ''}
`;
const js = `${header}
export const JEV_SET_VERSION = 'v10.0-draft';
export const FIX_MODE = ${JSON.stringify(D.fix_mode)};
export const DECISIONS_SHA256_12 = ${JSON.stringify(stamp)};

export const QUESTIONS = ${JSON.stringify(QUESTIONS, null, 2)};

export const CONCEPTS = ${JSON.stringify(CONCEPTS, null, 2)};
`;
fs.writeFileSync(path.join(V10, 'jev-set.js'), js);

const split = {
  version: 'split-v10.0-draft',
  decided_at: new Date().toISOString(),
  status: `DECIDED from data by assemble/decide.mjs (rule in that file), written by assemble/build.mjs. fix_mode ${D.fix_mode}. NOT FROZEN.`,
  rule: 'Jev first. Eligible = every Jev question passes lint.js (one question, explicit yes and no criteria, one condition, no presupposition, no degree, no indirection, no seen-film entity). A: an eligible candidate with precision >= 0.70 on >= 4 fires (magic films >= 0.60) and, where Sonnet was measured, recall >= Sonnet - 0.05 -> Jev (highest recall). S: Sonnet measured (>= 4 fires) and no eligible candidate within 0.05 of it on both precision and recall -> Sonnet. B: Sonnet measured and an eligible candidate ties it -> Jev (highest recall). C: Sonnet never asked or < 4 fires -> Jev (best Wilson lower bound that keeps recall within 0.05 of the v9 wording at 0.7).',
  data: {
    tournament: 'jevfirst/tournament/results.json (13 seen films, jev-1.13.0, $1.5361)',
    lint_fix: D.fix_note,
    dev_bias: 'all 13 films are seen films and the phrasings were chosen on them; the frozen held-out run is the real test',
  },
  not_split: "Scores (danger, harm, distress, share, resolution, laughs), modifiers (retold, imagined), the kind Choice, mention questions (m.*), film presence (fpl/fps), the claim checks, the split gate, the moment finder and the why check stay with Jev at their v9 wording (not part of the tournament).",
  sonnet_asked: sonnetUsed,
  sonnet_used: sonnetUsed,
  shadow: [],
  assign,
  concepts: Object.fromEntries(Object.entries(CONCEPTS).map(([k, c]) => [k, { owner: c.owner, v9_ids: c.v9_ids, film: c.film, jev: c.show, targets: c.targets.map((t) => `${t.layer}:${t.id ?? t.type}@${t.act}`), evidence: c.evidence }])),
  counts: {
    concepts: Object.keys(CONCEPTS).length,
    jev_concepts: Object.values(CONCEPTS).filter((c) => c.owner === 'jev').length,
    sonnet_concepts: Object.values(CONCEPTS).filter((c) => c.owner === 'sonnet').length,
    v9_ids_jev: universal.filter((id) => assign[id] === 'jev').length,
    v9_ids_sonnet: sonnetUsed.length,
    jev_questions: Object.keys(QUESTIONS).length,
    [D.fix_mode === "measured" ? "jev_questions_lint_fixed_measured" : "jev_questions_unmeasured_wording"]: Object.values(QUESTIONS).filter((q) => q.fix_of).length,
  },
};
fs.writeFileSync(path.join(V10, 'split.json'), JSON.stringify(split, null, 2));
console.log(`jev-set.js: ${Object.keys(QUESTIONS).length} questions, ${Object.keys(CONCEPTS).length} concepts; split.json: ${JSON.stringify(split.counts)}`);
